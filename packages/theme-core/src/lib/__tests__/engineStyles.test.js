// TC-57: the engine's own markup follows the semantic-class convention of doc 03 section 1 with
// ns = "pano" (`pano-post`, `pano-post__title`), committed as source (no build-time preprocessor for
// the engine), and the engine has its own scoped fallback sheet, generated by scripts/build-tokens.js.

const pkg = resolve(import.meta.dir, "..", "..", "..");
const lib = join(pkg, "src", "lib");
const NS = "pano";

/** Engine views: every file the generated view table points at, plus every .svelte under lib/views. */
function engineFiles() {
  const files = new Set();
  const table = readFileSync(join(lib, "views", "parts", "engine-views.generated.js"), "utf-8");
  for (const m of table.matchAll(/import\("([^"]+\.svelte)"\)/g)) files.add(resolve(lib, "views", "parts", m[1]));
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith(".svelte")) files.add(full);
    }
  };
  walk(join(lib, "views"));
  return [...files].sort();
}

const files = engineFiles();
const rel = (file) => relative(pkg, file).split("\\").join("/");
const views = files.map((file) => ({ name: basename(file, ".svelte"), file: rel(file) }));
const inScope = new Set(views.map((v) => v.file));

describe("engine semantic classes (doc 03 section 1, ns = pano)", () => {
  test("covers 57 engine files: the views, their parts and the registry components", () => {
    expect(files.length).toBe(57);
    for (const name of ["HomeView", "LoginView", "Post", "Navbar", "Footer", "RegisterForm", "Pagination", "Toast"]) {
      expect(views.some((v) => v.name === name)).toBe(true);
    }
  });

  test("`pano-plugin classes --fix` with ns pano has nothing left to write", () => {
    const missing = [];
    for (const file of files) {
      const view = basename(file, ".svelte");
      const source = readFileSync(file, "utf-8");
      const root = addRootClass(source, { ns: NS, view });
      const parts = addPartClasses(root.code, { ns: NS, view });
      for (const name of [...root.added, ...parts.added.map((a) => a.class)]) missing.push(`${rel(file)}: ${name}`);
    }
    expect(missing).toEqual([]);
  });

  test("a root element carries the view's root class in source", () => {
    expect(rootClassOf(NS, "ProfileView")).toBe("pano-profile-view");
    expect(readFileSync(join(lib, "views", "ProfileView.svelte"), "utf-8")).toContain("pano-profile-view");
    expect(readFileSync(join(lib, "views", "parts", "Post.svelte"), "utf-8")).toMatch(/pano-post[ '"]/);
    expect(readFileSync(join(lib, "views", "parts", "Post.svelte"), "utf-8")).toContain("pano-post__title");
  });

  test("existing class names stay: Bootstrap classes are still beside the semantic ones", () => {
    const source = readFileSync(join(lib, "views", "parts", "TicketStatus.svelte"), "utf-8");
    expect(source).toContain("pano-ticket-status pano-ticket-status__badge badge text-bg-success rounded-pill");
  });
});

