describe("engine style lint at badge level (checkStyles)", () => {
  const findings = checkStyles({ root: pkg, ns: NS, viewsDir: "src/lib", views, level: "badge" }).filter((f) => inScope.has(f.file));
  const where = (f) => `${f.file}:${f.line} ${f.rule}: ${f.message}`;

  test("the rules the semantic-class codemod answers are clean: root-class, part-coverage, part-prefix", () => {
    const errors = findings.filter((f) => ["root-class", "part-coverage", "part-prefix"].includes(f.rule) && f.level === "error");
    expect(errors.map(where)).toEqual([]);
  });

  test("the only views without a root class have no element root, and say so as a warning", () => {
    const roots = findings.filter((f) => f.rule === "root-class");
    expect(roots.every((f) => f.level === "warn")).toBe(true);
    expect(roots.map((f) => f.file).sort()).toEqual(NO_ROOT_ELEMENT.map((f) => `src/lib/${f}`).sort());
  });

  test("no finding beyond the known debt (class-allowed, style-block-scope, style-attr, no-bs-var, dynamic-class)", () => {
    const counts = {};
    for (const f of findings) {
      if (["root-class", "part-coverage", "part-prefix"].includes(f.rule)) continue;
      const key = `${f.file.replace("src/lib/", "")}|${f.rule}`;
      counts[key] = (counts[key] ?? 0) + 1;
    }
    const grown = Object.entries(counts)
      .filter(([key, n]) => n > (KNOWN_BADGE_DEBT[key] ?? 0))
      .map(([key, n]) => `${key}: ${n} (allowed ${KNOWN_BADGE_DEBT[key] ?? 0})`);
    expect(grown).toEqual([]);
  });

  test("the known-debt list names real findings only (drop an entry once its view is clean)", () => {
    const seen = new Set(findings.map((f) => `${f.file.replace("src/lib/", "")}|${f.rule}`));
    expect(Object.keys(KNOWN_BADGE_DEBT).filter((key) => !seen.has(key))).toEqual([]);
  });
});

describe("engine fallback sheet (assets/css/pano-fallback.css)", () => {
  const committed = readFileSync(join(ROOT, OUTPUTS.fallback), "utf-8");

  test("is generated at the path the engine links", () => {
    expect(OUTPUTS.fallback).toBe("packages/theme-core/assets/css/pano-fallback.css");
  });

  test("regenerating gives the committed file (drift)", () => {
    expect(build()[OUTPUTS.fallback]).toBe(committed);
  });

  test("is scoped to the pano namespace, layered, and has no !important", () => {
    expect(committed).toContain('@scope (.pano-fb[data-pano-fb="pano"]) to (.pano-fb-stop,');
    expect(committed).toContain("@layer pano-defaults, pano-fallback.components, pano-fallback.utilities, pano-plugin;");
    expect(committed).not.toContain("!important");
  });

  test("holds the Bootstrap classes the engine views use and the classes it builds from settings", () => {
    const base = readFileSync(join(ROOT, OUTPUTS.base), "utf-8");
    const used = scanEngine(baseClassSet(base));
    for (const c of ["navbar", "card", "btn", "form-control", "badge", "modal", "table", ...ENGINE_SAFELIST]) {
      expect(used).toContain(c);
      expect(committed).toContain(`.${c}`);
    }
    const sheet = postcss.parse(committed);
    expect(sheet.nodes.some((n) => n.type === "atrule" && n.name === "layer")).toBe(true);
  });

  test("the class list the sheet is built from is sorted and unique", () => {
    const base = readFileSync(join(ROOT, OUTPUTS.base), "utf-8");
    const used = scanEngine(baseClassSet(base));
    expect(used).toEqual([...used].sort());
    expect(new Set(used).size).toBe(used.length);
  });
});
